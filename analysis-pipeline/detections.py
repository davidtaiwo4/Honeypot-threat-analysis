"""
Generates Sigma and Suricata detection content directly from the pipeline's
own evidence (cluster.py's high-confidence clusters, hash.py's hash
summary) -- not hand-written rules that could silently drift from what the
data actually shows. Every rule below cites the exact evidence it's based
on in its description/reference field.

Two detection surfaces, matched to two different evidence types:

  1. Sigma rule for the RECON COMMAND behavior (command-level evidence:
     "uname -a && id" seen in the marker event). This is a BEHAVIOR
     detection -- it doesn't hardcode the campaign's IPs or hashes, so it
     would also catch a *new* attacker doing the same recon pattern, which
     is the actual point of a detection rule.

  2. Suricata rules for the CONCRETE IOCs (the 4 payload hashes from
     CLUSTER-001, generated dynamically from hash-summary.json so they
     never go stale relative to the actual hash-ledger). These are
     intentionally IOC-based (not behavioral) since file hash matching is
     inherently IOC-based -- documented as such, not conflated with the
     Sigma rule's behavioral coverage.
"""

import json


def build_sigma_recon_rule(marker_event_id: str, marker_session_id: str, evidence_marker: str) -> str:
    """Behavioral rule: post-auth reconnaissance command pattern, not tied
    to specific IOCs. YAML built by hand (not pyyaml) to avoid adding a
    dependency for a single small file; the structure is simple enough
    that string formatting is safe and auditable."""
    return f"""title: Post-Authentication Recon Command in Honeypot Session
id: {_stable_sigma_id('recon-uname-id', evidence_marker)}
status: experimental
description: >
    Detects a command-level reconnaissance pattern (uname + id chained
    together) observed immediately following successful authentication
    in a honeypot session. Behavioral rule -- not tied to a specific
    source IP or payload hash, so it also matches future actors using
    the same recon pattern, not just this replay's campaign.
references:
    - 'Derived from evidence event_id={marker_event_id}, session_id={marker_session_id}, evidence_marker={evidence_marker}'
    - 'See stix-bundle.json note object for the same locator'
author: soc-stage6-analysis-pipeline
date: {_today()}
logsource:
    category: honeypot
    product: t-pot
detection:
    selection_auth:
        action: auth_success
    selection_command:
        action: command
        command|contains|all:
            - 'uname'
            - 'id'
    timeframe: 5s
    condition: selection_auth followed by selection_command within timeframe
falsepositives:
    - Legitimate administrative session-establishment scripts that happen
      to run both commands for environment diagnostics (rare on a
      honeypot, since there are no legitimate admins by definition, but
      documented in case this rule is reused against real infrastructure)
level: high
tags:
    - attack.discovery
    - attack.t1082
"""


def build_suricata_payload_hash_rules(hash_summary: list, evidence_marker: str, sid_start: int = 1000001) -> str:
    """One Suricata rule per unique payload hash, generated from
    hash-summary.json so it can never drift from the actual hash ledger.
    Uses the filesha256 keyword (requires Suricata file extraction /
    file-store enabled on the sensor to populate the hash for comparison)."""
    lines = [
        "# Generated by detections.py from hash-summary.json -- do not hand-edit.",
        f"# evidence_marker={evidence_marker}",
        "# Requires Suricata file-store/file extraction enabled to populate filesha256 for comparison.",
        "",
    ]
    sid = sid_start
    for row in hash_summary:
        h = row["payload_sha256"]
        msg = (
            f"HONEYPOT CAMPAIGN Known payload hash {h[:16]}... "
            f"(seen {row['occurrence_count']}x across {row['distinct_source_ips']} IPs)"
        )
        rule = (
            f'alert tcp any any -> any any '
            f'(msg:"{msg}"; '
            f'filesha256:{h}; '
            f'reference:evidence,hash-ledger.csv; '
            f'classtype:trojan-activity; '
            f'sid:{sid}; rev:1;)'
        )
        lines.append(rule)
        sid += 1
    return "\n".join(lines) + "\n"


def build_suricata_cluster_watchlist_rule(cluster: dict, evidence_marker: str, sid: int = 1000101) -> str:
    """Watchlist rule for the high-confidence cluster's member IPs.
    Explicitly documented as IOC-based / context, not attribution, per
    the brief's guidance on reputation vs attribution -- these are RFC
    5737 documentation-range test IPs in this replay, not real-world
    addresses, and the rule content says so."""
    ip_list = ",".join(cluster["member_source_ips"])
    return (
        "# Generated by detections.py from clusters.json -- do not hand-edit.\n"
        f"# evidence_marker={evidence_marker}\n"
        f"# {cluster['cluster_id']}: {cluster['rationale']}\n"
        "# NOTE: source IPs are RFC 5737 documentation-range test addresses in this\n"
        "# replay dataset, not real-world attribution -- this rule is IOC-context,\n"
        "# not an actor-identification claim.\n"
        f'alert ip [{ip_list}] any -> $HOME_NET any '
        f'(msg:"Traffic from {cluster["cluster_id"]} known campaign infrastructure '
        f'{len(cluster["member_source_ips"])} IPs shared payload hash evidence"; '
        f'reference:evidence,clusters.json; '
        f'classtype:trojan-activity; '
        f'sid:{sid}; rev:1;)\n'
    )


def _stable_sigma_id(seed: str, evidence_marker: str) -> str:
    import uuid
    namespace = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")
    return str(uuid.uuid5(namespace, f"sigma|{seed}|{evidence_marker}"))


def _today() -> str:
    from datetime import date
    return date.today().isoformat()


def write_all_detections(out_dir: str, clusters_dict: dict, hash_summary: list,
                          evidence_marker: str, marker_event_id: str, marker_session_id: str) -> list:
    import os
    written = []

    sigma_text = build_sigma_recon_rule(marker_event_id, marker_session_id, evidence_marker)
    sigma_path = os.path.join(out_dir, "sigma-recon-command.yml")
    with open(sigma_path, "w") as f:
        f.write(sigma_text)
    written.append(sigma_path)

    suricata_hashes_text = build_suricata_payload_hash_rules(hash_summary, evidence_marker)
    suricata_hashes_path = os.path.join(out_dir, "suricata-known-payload-hashes.rules")
    with open(suricata_hashes_path, "w") as f:
        f.write(suricata_hashes_text)
    written.append(suricata_hashes_path)

    high_conf = [c for c in clusters_dict["clusters"] if c["evidence_type"] == "shared_payload_hash"]
    for i, cluster in enumerate(high_conf):
        watchlist_text = build_suricata_cluster_watchlist_rule(cluster, evidence_marker, sid=1000101 + i)
        watchlist_path = os.path.join(out_dir, f"suricata-{cluster['cluster_id'].lower()}-watchlist.rules")
        with open(watchlist_path, "w") as f:
            f.write(watchlist_text)
        written.append(watchlist_path)

    return written
